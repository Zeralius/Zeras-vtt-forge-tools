#!/usr/bin/env node
// Regenerates the bundle module — the one people install when they just want everything.
//
// Foundry can't install a repository, only a manifest. But a module is allowed to declare other
// modules as requirements, and when you install it Foundry offers to pull those in too. So the
// bundle is an empty module whose entire job is to list the real ones.
//
//   node scripts/bundle.mjs           regenerate it
//   node scripts/bundle.mjs --check   fail if it's out of date (this is what CI runs)
import fs from 'node:fs';
import path from 'node:path';
import {
    BUNDLE_ID, listModuleIds, moduleDir, manifestPath, readManifest, writeManifest,
    manifestUrl, downloadUrl, projectUrl
} from './lib/modules.mjs';

const check = process.argv.includes('--check');
const members = listModuleIds({ includeBundle: false });

// Keep whatever version the bundle is already on; it gets bumped by the release script like
// anything else. Only the dependency list is generated.
let version = '1.0.0';
if (fs.existsSync(manifestPath(BUNDLE_ID))) version = readManifest(BUNDLE_ID).version;

const bundle = {
    id: BUNDLE_ID,
    title: "Zera's VTT Forge Tools",
    description: `Installs every module in Zera's VTT Forge Tools at once: ${members.join(', ')}. `
        + 'This module has no functionality of its own — it exists so you only have to paste one '
        + 'manifest URL. You can safely disable it afterwards; the modules it pulled in stay installed.',
    authors: [{ name: 'Zeralius' }],
    version,
    compatibility: { minimum: '13', verified: '14' },
    relationships: {
        requires: members.map(id => {
            const manifest = readManifest(id);
            return {
                id,
                type: 'module',
                manifest: manifestUrl(id),
                compatibility: { minimum: manifest.version }
            };
        })
    },
    url: projectUrl(),
    manifest: manifestUrl(BUNDLE_ID),
    download: downloadUrl(BUNDLE_ID, version)
};

const expected = `${JSON.stringify(bundle, null, 2)}\n`;
const current = fs.existsSync(manifestPath(BUNDLE_ID)) ? fs.readFileSync(manifestPath(BUNDLE_ID), 'utf8') : null;

if (check) {
    if (current !== expected) {
        console.error(`\n✗ modules/${BUNDLE_ID}/module.json is out of date.`);
        console.error(`  It should list: ${members.join(', ')}`);
        console.error(`  Run "npm run bundle" and commit the result.\n`);
        process.exit(1);
    }
    console.log(`✓ bundle is up to date (${members.length} module${members.length === 1 ? '' : 's'}: ${members.join(', ')})`);
    process.exit(0);
}

fs.mkdirSync(moduleDir(BUNDLE_ID), { recursive: true });
writeManifest(BUNDLE_ID, bundle);
fs.writeFileSync(path.join(moduleDir(BUNDLE_ID), 'README.md'), `# Zera's VTT Forge Tools (bundle)

Install this and Foundry will offer to install every module in the collection along with it:

${members.map(id => `- \`${id}\``).join('\n')}

It has no code of its own. Once the others are installed you can disable or uninstall this one
and they'll keep working.

**Do not edit \`module.json\` here by hand** — it's generated by \`npm run bundle\`.
`, 'utf8');

console.log(`✓ bundle regenerated with ${members.length} module${members.length === 1 ? '' : 's'}: ${members.join(', ')}`);
